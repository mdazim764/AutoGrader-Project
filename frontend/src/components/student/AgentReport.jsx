import { CheckCircle, XCircle, Brain, AlertTriangle, UserCheck, MessageSquare } from 'lucide-react';

export default function AgentReport({ result, loading, error }) {
  if (error) {
    return <div className="p-4 bg-red-900/30 border border-red-800 rounded-lg text-red-400 text-sm mb-4">{error}</div>;
  }

  if (loading) {
    return (
      <div className="flex-1 flex flex-col items-center justify-center">
        <div className="w-10 h-10 border-4 border-blue-500 border-t-transparent rounded-full animate-spin mb-4"></div>
        <p className="text-blue-400 font-medium animate-pulse">Running multiple AI agents...</p>
      </div>
    );
  }

  if (!result) {
    return (
      <div className="flex-1 flex items-center justify-center text-gray-500 italic">
        Submit your code to see the detailed agent analysis.
      </div>
    );
  }

  const metrics = Array.isArray(result.report?.metrics) ? result.report.metrics : [];
  const report = result.report || {};
  const firstPass = report.first_pass || {};
  const usefulness = report.usefulness_limitations || {};
  const reviewOnlyMetrics = metrics.filter((metric) => metric.reviewOnly);
  const integrity = report.integrity || {};
  const formatMetricReport = (metric, index) => {
    const details = metric?.details && typeof metric.details === 'object' ? metric.details : {};
    const evidence = metric?.evidence && typeof metric.evidence === 'object' ? metric.evidence : {};
    const cases = Array.isArray(details)
      ? details
      : Array.isArray(details.details)
        ? details.details
        : Array.isArray(evidence.details)
          ? evidence.details
          : [];
    const lines = [
      `Metric ${index + 1}: ${metric.name || 'unnamed'}`,
      `Status: ${metric.status || 'UNKNOWN'}`,
      `Score: ${metric.score == null ? 'N/A' : `${Math.round(metric.score * 100)}%`}`,
      `Weight: ${metric.weight == null ? 'N/A' : metric.weight}`,
      `Contribution: ${metric.contribution == null ? 'N/A' : metric.contribution}`,
    ];

    if (metric.feedback) lines.push(`Feedback: ${metric.feedback}`);
    if (metric.reviewOnly) lines.push('Review only: this signal does not prove misconduct or directly change the grade.');
    if (cases.length) {
      lines.push('Test evidence:');
      cases.forEach((testCase, caseIndex) => {
        lines.push(`  Case ${caseIndex + 1} (${testCase.case || 'unnamed'}): ${testCase.passed ? 'PASSED' : 'FAILED'}`);
        lines.push(`    Input: ${testCase.input ?? 'N/A'}`);
        lines.push(`    Expected: ${testCase.expected ?? 'N/A'}`);
        lines.push(`    Actual: ${testCase.actual ?? testCase.got ?? 'N/A'}`);
      });
    }
    if (metric.aiFeedback) {
      lines.push(`Explanation: ${metric.aiFeedback.explanation || 'N/A'}`);
      if (metric.aiFeedback.root_cause) lines.push(`Likely cause: ${metric.aiFeedback.root_cause}`);
      lines.push(`Hint: ${metric.aiFeedback.hint || 'N/A'}`);
      if (metric.aiFeedback.counter_case) {
        lines.push(`Counterexample input: ${metric.aiFeedback.counter_case.input || 'N/A'}`);
        lines.push(`Counterexample expected: ${metric.aiFeedback.counter_case.expected || 'N/A'}`);
      }
    }
    if (Object.keys(evidence).length) {
      lines.push(`Evidence details: ${JSON.stringify(evidence)}`);
    }
    if (metric.errors?.length) lines.push(`Errors: ${metric.errors.join('; ')}`);
    return lines.join('\n');
  };
  const downloadReport = (format) => {
    const text = format === 'json'
      ? JSON.stringify(report, null, 2)
      : [
        'Agentic AutoGrader Student Report',
        '================================',
        `Submission: ${report.submission?.id || 'unknown'}`,
        `Overall score: ${result.finalScore ?? report.overall_score ?? 'N/A'}/100`,
        `Review-only signals: ${reviewOnlyMetrics.length ? `${reviewOnlyMetrics.length} detected/analyzed; marks affected: 0` : 'None configured'}`,
        `Integrity decision: ${integrity.decision || 'No integrity penalty recorded'}`,
        `Integrity marks deducted: ${integrity.marks_deducted ?? 0}`,
        `Report schema: ${report.schema_version || 'N/A'}`,
        `Generated by: ${report.generated_by || 'N/A'}`,
        '',
        'Reproducibility metadata:',
        `- Submission hash: ${report.submission?.hash || 'N/A'}`,
        `- Rules hash: ${report.rules_hash || 'N/A'}`,
        `- Test-set hash: ${report.test_set_hash || 'N/A'}`,
        '',
        'First-pass execution:',
        `- Compiled: ${firstPass.success ?? 'N/A'}`,
        `- Warnings: ${firstPass.warnings || 'None recorded'}`,
        `- Timed out: ${firstPass.timedOut ?? 'N/A'}`,
        `- Crashed: ${firstPass.crashed ?? 'N/A'}`,
        '',
        'Metric results and evidence:',
        ...metrics.map(formatMetricReport),
        '',
        'Review flags:',
        ...(report.flags?.length ? report.flags.map((flag) => `- ${flag}`) : ['- None']),
        '',
        'Tool versions:',
        JSON.stringify(report.tool_versions || {}, null, 2),
        '',
        'Usefulness:',
        ...(usefulness.usefulness?.length ? usefulness.usefulness.map((item) => `- ${item}`) : ['- Not recorded']),
        '',
        'Limitations:',
        ...(usefulness.limitations?.length ? usefulness.limitations.map((item) => `- ${item}`) : ['- Not recorded']),
      ].join('\n');
    const blob = new Blob([text], { type: format === 'json' ? 'application/json' : 'text/plain' });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = `autograder-${report.submission?.id || 'report'}.${format}`;
    anchor.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6 overflow-y-auto pr-2 pb-4">
      
      {/* 🔥 FINAL SCORE (Rounded off) 🔥 */}
      <div className="bg-gray-950 p-6 rounded-xl border border-gray-800 text-center">
        <p className="text-gray-400 text-sm font-semibold uppercase tracking-wider mb-1">Final Score</p>
        <h3 className={`text-5xl font-extrabold ${result.finalScore >= 80 ? 'text-green-400' : result.finalScore >= 50 ? 'text-yellow-400' : 'text-red-400'}`}>
          {result.finalScore === null || result.finalScore === undefined ? '--' : Math.round(result.finalScore)}<span className="text-2xl text-gray-600">/100</span>
        </h3>
        <div className="mt-4 flex justify-center gap-2">
          <button type="button" onClick={() => downloadReport('json')} className="rounded-lg border border-slate-700 px-3 py-2 text-xs text-slate-300 transition hover:border-indigo-400 hover:text-white">Download JSON</button>
          <button type="button" onClick={() => downloadReport('txt')} className="rounded-lg border border-slate-700 px-3 py-2 text-xs text-slate-300 transition hover:border-indigo-400 hover:text-white">Download text report</button>
        </div>
      </div>

      {result.status === 'FAILED' && (
        <div className="rounded-lg border border-red-800 bg-red-950/30 p-4 text-sm text-red-300">
          Grading failed before a complete report could be generated. Please review the submission status or try again.
        </div>
      )}

      <div className="rounded-xl border border-slate-800 bg-slate-950/80 p-5">
        <div className="mb-4 flex items-center justify-between">
          <div>
            <h4 className="font-semibold text-slate-200">Grading evidence</h4>
            <p className="text-xs text-slate-500">Reproducibility and first-pass metadata for this report.</p>
          </div>
          <span className="rounded-full bg-indigo-500/15 px-3 py-1 text-xs text-indigo-300">
            Schema {report.schema_version || 'unknown'}
          </span>
        </div>
        <details className="mb-4">
          <summary className="cursor-pointer text-xs font-semibold text-slate-300">View report integrity fingerprints</summary>
          <div className="mt-3 grid gap-3 text-xs text-slate-400 md:grid-cols-2">
            <div><span className="text-slate-500">Submission hash:</span> <code className="break-all text-slate-300">{report.submission?.hash || 'Unavailable'}</code></div>
            <div><span className="text-slate-500">Rules hash:</span> <code className="break-all text-slate-300">{report.rules_hash || 'Unavailable'}</code></div>
            <div><span className="text-slate-500">Test set hash:</span> <code className="break-all text-slate-300">{report.test_set_hash || 'Unavailable'}</code></div>
            <div><span className="text-slate-500">Generated by:</span> <span className="text-slate-300">{report.generated_by || 'Unavailable'}</span></div>
          </div>
        </details>
        <div className="mt-4 grid gap-2 text-xs md:grid-cols-4">
          {[
            ['Compiled', firstPass.success],
            ['Warnings', firstPass.warnings ? 'Present' : 'None recorded'],
            ['Timeout', firstPass.timedOut ? 'Yes' : 'No'],
            ['Crash', firstPass.crashed ? 'Yes' : 'No'],
          ].map(([label, value]) => (
            <div key={label} className="rounded-lg border border-slate-800 bg-slate-900 p-3">
              <span className="block text-slate-500">{label}</span>
              <span className="mt-1 block font-medium text-slate-200">{String(value ?? 'Not recorded')}</span>
            </div>
          ))}
        </div>
        {Object.keys(report.tool_versions || {}).length > 0 && (
          <details className="mt-4">
            <summary className="cursor-pointer text-xs font-semibold text-slate-300">Tool versions</summary>
            <pre className="mt-2 overflow-auto rounded-lg bg-slate-900 p-3 text-xs text-slate-400">{JSON.stringify(report.tool_versions, null, 2)}</pre>
          </details>
        )}
      </div>

      {Array.isArray(report.flags) && report.flags.length > 0 && (
        <div className="rounded-xl border border-amber-900/50 bg-amber-950/20 p-4">
          <h4 className="font-semibold text-amber-300">Review flags</h4>
          <p className="mt-1 text-xs text-amber-200/80">
            {integrity.exact_peer_match
              ? `Exact peer match: ${integrity.marks_deducted ?? 0} marks deducted by integrity policy.`
              : 'Non-integrity review signals affected 0 marks.'}
          </p>
          {integrity.matched_submission_student?.name && (
            <p className="mt-2 text-xs text-rose-200">
              Matched submission owner: <span className="font-semibold">{integrity.matched_submission_student.name}</span>
            </p>
          )}
          <div className="mt-2 flex flex-wrap gap-2">
            {report.flags.map((flag) => <span key={flag} className="rounded-full bg-amber-500/15 px-3 py-1 text-xs text-amber-200">{flag}</span>)}
          </div>
        </div>
      )}

      {metrics.map((metric, idx) => {
        const details = metric?.details && typeof metric.details === 'object'
          ? metric.details
          : {};
        const evidence = metric?.evidence && typeof metric.evidence === 'object'
          ? metric.evidence
          : {};
        const logicalDetails = Array.isArray(details)
          ? details
          : Array.isArray(details.details)
            ? details.details
            : Array.isArray(evidence.details)
              ? evidence.details
              : [];
        const feedback = metric?.feedback || details.feedback || '';

        // 1. Compilation Error
        if (metric.name === 'compilation_error') {
          return (
            <div key={idx} className="space-y-4">
              <div className="bg-red-950/40 border border-red-900 rounded-lg p-4">
                <h4 className="flex items-center gap-2 font-bold text-red-500 mb-2 border-b border-red-900/50 pb-2">
                  <XCircle size={18} /> Compilation Failed
                </h4>
                <pre className="text-xs font-mono text-red-300 whitespace-pre-wrap p-2 bg-black/30 rounded">{details.rawError || evidence.output || 'No compiler output was recorded.'}</pre>
              </div>
              <div className="bg-orange-950/30 border border-orange-900/50 rounded-lg p-4">
                <h4 className="flex items-center gap-2 font-semibold text-orange-400 mb-3"><Brain size={18} /> AI Syntax Hints</h4>
                <ul className="list-disc list-inside space-y-2 text-sm text-gray-300 mb-4">
                  {(Array.isArray(details.aiHints) ? details.aiHints : []).map((hint, hIdx) => <li key={hIdx}>{hint}</li>)}
                </ul>
              </div>
            </div>
          );
        }

        // 2. Logical Cases & AI Hints
        if (metric.name === 'logical') {
          return (
            <div key={idx} className="space-y-3">
              <h4 className="flex items-center gap-2 font-semibold text-blue-300 text-lg border-b border-gray-800 pb-2">
                <CheckCircle size={20} /> I/O Edge Cases
              </h4>
              <div className="space-y-2">
                {logicalDetails.map((tc, tIdx) => (
                  <div key={tIdx} className={`p-3 rounded-lg border text-sm flex justify-between items-center ${tc.passed ? 'bg-green-950/30 border-green-900/50 text-green-300' : 'bg-red-950/30 border-red-900/50 text-red-300'}`}>
                    <span><span className="font-semibold capitalize">{tc.case}</span> Test
                      {(tc.input || tc.expected || tc.got) && <span className="mt-1 block text-xs text-slate-500">Input: {tc.input || '—'} · Expected: {tc.expected || '—'} · Actual: {tc.actual || tc.got || '—'}</span>}
                      {!tc.passed && <span className="mt-1 block text-xs font-semibold uppercase tracking-wide text-rose-300">{String(tc.failureReason || (tc.timedOut ? 'TIMEOUT' : 'WRONG_OUTPUT')).replace(/_/g, ' ')}</span>}
                    </span>
                    <span>{tc.passed ? '✅ Passed' : tc.timedOut ? '❌ Timed out' : `❌ Failed (Got: ${tc.actual || tc.got || 'no output'})`}</span>
                  </div>
                ))}
              </div>

              {/* 🔥 AI Counter Case Rendering 🔥 */}
              {metric.aiFeedback && (
                <div className="mt-4 p-4 bg-orange-950/30 border border-orange-900/50 rounded-lg">
                  <h5 className="font-bold text-orange-400 mb-2 flex items-center gap-2">
                    <Brain size={16} /> AI Logic Hint
                  </h5>
                  <div className="mb-3 space-y-2 text-sm text-gray-300">
                    <p><span className="font-semibold text-orange-300">What failed:</span> {metric.aiFeedback.explanation || 'The program did not produce the expected result.'}</p>
                    {metric.aiFeedback.root_cause && <p><span className="font-semibold text-orange-300">Likely cause:</span> {metric.aiFeedback.root_cause}</p>}
                    <p><span className="font-semibold text-orange-300">How to improve:</span> {metric.aiFeedback.hint || 'Trace the failing input through the loop condition, initialization, and output statement.'}</p>
                  </div>
                  <div className="bg-black/40 p-3 rounded border border-orange-900/30">
                    <p className="text-xs text-orange-300 uppercase font-bold tracking-wider mb-1">🚨 Counter Test Case Generated</p>
                    <div className="flex gap-4 text-sm font-mono">
                      <div><span className="text-gray-500">Input:</span> <span className="text-blue-300">"{metric.aiFeedback.counter_case.input}"</span></div>
                      <div><span className="text-gray-500">Expected:</span> <span className="text-green-300">"{metric.aiFeedback.counter_case.expected}"</span></div>
                    </div>
                  </div>
                </div>
              )}
            </div>
          );
        }

        // 3. Complexity
        if (metric.name === 'complexity') {
            return (
              <div key={idx} className="bg-gray-950 p-4 rounded-lg border border-gray-800">
                <h4 className="flex items-center gap-2 font-semibold text-yellow-400 mb-2"><Brain size={18}/> Complexity Analysis</h4>
                <p className="text-gray-300 text-sm mb-1">Estimated: <span className="font-mono bg-gray-900 px-2 py-1 rounded text-yellow-300">{details.estimated || evidence.estimated || 'Unavailable'}</span></p>
                <p className="text-gray-400 text-xs">{feedback || 'No complexity feedback was recorded.'}</p>
              </div>
            );
        }

        // 4. 🔥 Readability / Code Review 🔥
        if (metric.name === 'readability') {
            return (
              <div key={idx} className="bg-gray-950 p-4 rounded-lg border border-gray-800">
                <h4 className="flex items-center gap-2 font-semibold text-purple-400 mb-2">
                  <MessageSquare size={18} /> AI Code Review
                </h4>
                <p className="text-gray-300 text-sm leading-relaxed">{feedback || 'No readability feedback was recorded.'}</p>
              </div>
            );
        }

        // 5. 🔥 AI Detection / Plagiarism 🔥
        if (metric.name === 'ai_detection') {
            const { is_ai, confidence, reason } = { ...evidence, ...details };
            return (
              <div key={idx} className={`p-4 rounded-lg border mt-4 ${is_ai ? 'bg-red-950/20 border-red-900/50' : 'bg-teal-950/20 border-teal-900/50'}`}>
                <h4 className={`flex items-center gap-2 font-bold mb-2 ${is_ai ? 'text-red-400' : 'text-teal-400'}`}>
                  {is_ai ? <AlertTriangle size={18} /> : <UserCheck size={18} />}
                  {is_ai ? 'AI-style Signal Detected' : 'No AI-style Signal Detected'}
                  <span className="text-xs font-normal opacity-70 px-2 py-0.5 bg-black/30 rounded-full ml-auto">
                    {confidence}% Confidence
                  </span>
                </h4>
                <p className="text-sm text-gray-300"><span className="font-semibold opacity-80">Analysis:</span> {reason}</p>
                {evidence.analysis_mode === 'fallback' && (
                  <p className="mt-2 text-xs text-amber-300">
                    LLM review was unavailable. This result used deterministic source-trait analysis and did not affect marks.
                  </p>
                )}
              </div>
            );
        }

        return (
          <div key={idx} className="rounded-lg border border-gray-800 bg-gray-950 p-4">
            <div className="flex items-center justify-between gap-3">
              <h4 className="font-semibold capitalize text-slate-200">
                {String(metric.name || 'metric').replace(/_/g, ' ')}
              </h4>
              <span className="rounded-full bg-slate-800 px-2 py-1 text-xs text-slate-300">
                {metric.status || 'AVAILABLE'}
              </span>
            </div>
            <p className="mt-2 text-sm text-slate-400">
              {metric.feedback || 'No additional feedback was recorded.'}
            </p>
            <details className="mt-3">
              <summary className="cursor-pointer text-xs text-slate-500">View evidence</summary>
              <pre className="mt-2 max-h-64 overflow-auto rounded-lg bg-slate-900 p-3 text-xs text-slate-400">{JSON.stringify(metric.evidence || {}, null, 2)}</pre>
            </details>
            {metric.reviewOnly && (
              <p className="mt-2 text-xs text-amber-300">
                Review signal only; this does not prove misconduct or directly change the grade.
              </p>
            )}
          </div>
        );
      })}

      {(Array.isArray(usefulness.usefulness) || Array.isArray(usefulness.limitations)) && (
        <div className="grid gap-4 md:grid-cols-2">
          <div className="rounded-xl border border-emerald-900/50 bg-emerald-950/20 p-4">
            <h4 className="font-semibold text-emerald-300">Usefulness</h4>
            <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-slate-300">{(usefulness.usefulness || []).map((item) => <li key={item}>{item}</li>)}</ul>
          </div>
          <div className="rounded-xl border border-slate-800 bg-slate-950/80 p-4">
            <h4 className="font-semibold text-slate-300">Limitations</h4>
            <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-slate-400">{(usefulness.limitations || []).map((item) => <li key={item}>{item}</li>)}</ul>
          </div>
        </div>
      )}
    </div>
  );
}